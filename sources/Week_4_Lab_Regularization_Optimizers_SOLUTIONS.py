    "# Summary\n",
    "\n",
    "## Key Concepts Covered\n",
    "\n",
    "**Regularization Techniques:**\n",
    "- L1 (Lasso): Sparse weights, feature selection\n",
    "- L2 (Ridge/Weight Decay): Small, distributed weights\n",
    "- Early Stopping: Stop when validation loss increases\n",
    "- Dropout: Random neuron dropping, prevents co-adaptation\n",
    "- Batch Normalization: Normalize layer inputs, enables higher LR\n",
    "\n",
    "**Optimization Algorithms:**\n",
    "- SGD: Basic gradient descent\n",
    "- Momentum: Accumulates velocity, faster convergence\n",
    "- Adam: Adaptive learning rates + momentum\n",
    "- AdamW: Adam with decoupled weight decay\n",
    "\n",
    "## Key Equations\n",
    "\n",
    "| Method | Update Rule |\n",
    "|--------|-------------|\n",
    "| L2 Regularization | $\\mathcal{L}_{reg} = \\mathcal{L} + \\frac{\\lambda}{2}\\|\\theta\\|_2^2$ |\n",
    "| Dropout | $\\tilde{h} = \\frac{m \\odot h}{1-p}$, $m \\sim \\text{Bernoulli}(1-p)$ |\n",
    "| Batch Norm | $\\hat{x} = \\frac{x - \\mu_B}{\\sqrt{\\sigma_B^2 + \\epsilon}}$, $y = \\gamma\\hat{x} + \\beta$ |\n",
    "| SGD + Momentum | $v_t = \\beta v_{t-1} + g_t$, $\\theta_{t+1} = \\theta_t - \\alpha v_t$ |\n",
    "| Adam | $\\theta_{t+1} = \\theta_t - \\frac{\\alpha}{\\sqrt{\\hat{v}_t} + \\epsilon}\\hat{m}_t$ |\n",
    "\n",
    "## Important Reminders\n",
    "\n",
    "- Use `model.train()` during training (dropout ON, BN uses batch stats)\n",
    "- Use `model.eval()` during inference (dropout OFF, BN uses running stats)\n",
    "- Always use `torch.no_grad()` during evaluation"
