        "def find_misclassifications(model, test_loader, device, n_errors=10):\n",
        "    model.eval()\n",
        "    \n",
        "    misclassified_images = []\n",
        "    misclassified_labels = []\n",
        "    misclassified_preds = []\n",
        "    misclassified_probs = []\n",
        "    \n",
        "    with torch.no_grad():\n",
        "        for images, labels in test_loader:\n",
        "            images, labels = images.to(device), labels.to(device)\n",
        "            outputs = model(images)\n",
        "            _, predictions = outputs.max(1)\n",
        "            probabilities = F.softmax(outputs, dim=1)\n",
        "            \n",
        "            mask = predictions != labels\n",
        "            \n",
        "            if mask.sum() > 0:\n",
        "                misclassified_images.extend(images[mask].cpu())\n",
        "                misclassified_labels.extend(labels[mask].cpu())\n",
        "                misclassified_preds.extend(predictions[mask].cpu())\n",
        "                \n",
        "                for i in range(mask.sum()):\n",
        "                    idx = torch.where(mask)[0][i]\n",
        "                    pred_class = predictions[idx]\n",
        "                    conf = probabilities[idx, pred_class].cpu().item()\n",
        "                    misclassified_probs.append(conf)\n",
        "            \n",
        "            if len(misclassified_images) >= n_errors:\n",
        "                break\n",
