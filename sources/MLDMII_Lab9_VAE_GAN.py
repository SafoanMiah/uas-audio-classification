    "---\n",
    "# Part 2 — Generative Adversarial Networks (GAN)\n",
    "\n",
    "**Recap from lecture:**\n",
    "A GAN trains two networks in opposition. The **Generator** $G$ maps random noise $z$ to fake images. The **Discriminator** $D$ scores images as real or fake. Their losses are:\n",
    "\n",
    "$$\\mathcal{L}_D = -\\left[\\log D(x) + \\log(1 - D(G(z)))\\right]$$\n",
