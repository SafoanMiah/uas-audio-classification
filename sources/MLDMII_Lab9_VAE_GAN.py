    "---\n",
    "## 2.4 The Two-Step GAN Training Loop\n",
    "\n",
    "Every mini-batch performs **two** backward passes:\n",
    "\n",
    "```\n",
    "Step 1 — Update D  (G frozen via .detach())\n",
    "   L_D = BCE(D(x_real), 1) + BCE(D(G(z).detach()), 0)\n",
    "   optimizer_D.zero_grad() → L_D.backward() → optimizer_D.step()\n",
    "\n",
    "Step 2 — Update G  (D frozen, but gradient flows THROUGH it)\n",
    "   L_G = BCE(D(G(z)), 1)   ← no .detach() on G(z)\n",
    "   optimizer_G.zero_grad() → L_G.backward() → optimizer_G.step()\n",
    "```\n",
    "\n",
    "After each epoch we log $D(x)$ (should stay near 0.5–0.7) and $D(G(z))$ (should rise as G improves)."
